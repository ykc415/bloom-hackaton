const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, ko, ja };
type Vars = Record<string, string | number>;
const fill = (text: string, vars?: Vars) => (vars ? text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : text);
const PluralKey = (key: string) => key as MessageKey;

type I18n = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, vars?: Vars) => string;
  /** Picks `<key>_one` or `<key>_other` by count. */
  tc: (key: string, count: number, vars?: Vars) => string;
  dateLocale: string;
};

const I18nContext = createContext<I18n | null>(null);
const STORAGE_KEY = 'magent.locale';

function detectLocale(): Locale {
  if (typeof window === 'undefined') return 'en';
  let stored: string | null = null;
  try { stored = localStorage.getItem(STORAGE_KEY); } catch { /* storage unavailable */ }
  if (stored === 'ko' || stored === 'en' || stored === 'ja') return stored;
  const browser = navigator.language.toLowerCase();
  return browser.startsWith('ko') ? 'ko' : browser.startsWith('ja') ? 'ja' : 'en';
}

// The page renders only a text-free boot screen on the server, so reading the stored
// locale during the first client render cannot cause a hydration mismatch.
export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detectLocale);
  useEffect(() => { document.documentElement.lang = locale; }, [locale]);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    try { localStorage.setItem(STORAGE_KEY, next); } catch { /* storage unavailable */ }
  }, []);

  const value = useMemo<I18n>(() => {
    const dict = dictionaries[locale];
    const t = (key: MessageKey, vars?: Vars) => fill(dict[key], vars);
    const tc = (key: string, count: number, vars?: Vars) => fill(dict[PluralKey(`${key}_${count === 1 ? 'one' : 'other'}`)], { count, ...vars });
    return { locale, setLocale, t, tc, dateLocale: { ko: 'ko-KR', en: 'en-US', ja: 'ja-JP' }[locale] };
  }, [locale, setLocale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nProvider');
  return value;
}
